// Generates supabase/seed.sql from the placeholder catalog so there is one source of truth (SEED_ITEMS).
// Run: npm run gen:seed
import { writeFileSync } from 'node:fs';
import { DEFAULT_SETTINGS } from '../supabase/functions/_shared/settings.ts';
import { SEED_ITEMS, SEED_STARTERS, SEED_ZIPS } from '../supabase/functions/_shared/seed-catalog.ts';
import { itemToRow } from '../supabase/functions/_shared/mappers.ts';

class Json { constructor(readonly v: unknown) {} }
const lit = (v: unknown): string => {
  if (v instanceof Json) return `'${JSON.stringify(v.v).replace(/'/g, "''")}'::jsonb`;
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${(typeof v === 'string' ? v : JSON.stringify(v)).replace(/'/g, "''")}'`;
};
const upsert = (table: string, pk: string, rows: Record<string, unknown>[]) => {
  const cols = Object.keys(rows[0]);
  const vals = rows.map((r) => `(${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n  ');
  const set = cols.filter((c) => c !== pk).map((c) => `${c} = excluded.${c}`).join(', ');
  return `insert into public.${table} (${cols.join(', ')}) values\n  ${vals}\non conflict (${pk}) do update set ${set};\n`;
};

const out = [
  '-- GENERATED by `npm run gen:seed` from supabase/functions/_shared/seed-catalog.ts. PLACEHOLDER data: do not launch with it.',
  '-- Real data: fill wayfinder/owner-catalog-sheet.csv and use `npm run import:catalog` (or Admin > Catalog > Import CSV).',
  upsert('items', 'id', SEED_ITEMS.map((i) => { const r = itemToRow(i); return { ...r, tags: new Json(r['tags']) }; })),
  upsert('starter_bags', 'id', SEED_STARTERS.map((s) => ({ id: s.id, name: s.name, blurb: s.blurb, items: new Json(s.items), sort: s.sort, active: true }))),
  upsert('zips', 'zip', SEED_ZIPS),
  upsert('settings', 'key', Object.entries(DEFAULT_SETTINGS).map(([key, value]) => ({ key, value: new Json(value) }))),
  '-- After the owner signs in once, allow them to use the admin (replace with the dedicated Gmail):',
  "-- insert into public.admins (email) values ('your-dedicated-gmail@gmail.com') on conflict do nothing;",
].join('\n');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out + '\n');
console.log(`wrote supabase/seed.sql (${SEED_ITEMS.length} items, ${SEED_ZIPS.length} zips)`);
