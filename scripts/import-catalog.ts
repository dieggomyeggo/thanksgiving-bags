// Turns the owner's filled catalog sheet into SQL you paste into the Supabase SQL editor (nothing is sent anywhere).
// Usage: npm run import:catalog -- wayfinder/owner-catalog-sheet.csv [out.sql]
// Or import in the browser: Admin > Catalog > Import CSV (same parser).
import { readFileSync, writeFileSync } from 'node:fs';
import { catalogFromCsv } from '../supabase/functions/_shared/catalog-csv.ts';
import { assertPricingFloor } from '../supabase/functions/_shared/pricing.ts';
import { itemToRow } from '../supabase/functions/_shared/mappers.ts';

const [src = '../wayfinder/owner-catalog-sheet.csv', dest = 'supabase/import-catalog.sql'] = process.argv.slice(2);
const { items, warnings } = catalogFromCsv(readFileSync(src, 'utf8'));
for (const w of warnings) console.warn('warning:', w);
if (!items.length) {
  console.error('No rows with Include? = Y were imported. Fill the sheet first.');
  process.exit(1);
}
assertPricingFloor(items);

const lit = (v: unknown): string =>
  v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v)
    : `'${(typeof v === 'string' ? v : JSON.stringify(v)).replace(/'/g, "''")}'${typeof v === 'object' ? '::jsonb' : ''}`;
const rows = items.map(itemToRow);
const cols = Object.keys(rows[0]);
const sql = [
  '-- GENERATED by import-catalog.ts. Replaces the placeholder catalog: items not in the sheet are deactivated.',
  'update public.items set active = false;',
  `insert into public.items (${cols.join(', ')}) values`,
  rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n'),
  `on conflict (id) do update set ${cols.filter((c) => c !== 'id').map((c) => `${c} = excluded.${c}`).join(', ')};`,
  '-- Starter bags reference item ids; check them in Admin > Catalog afterwards.',
].join('\n');
writeFileSync(dest, sql + '\n');
console.log(`wrote ${dest}: ${items.length} items, floor verified for all`);
